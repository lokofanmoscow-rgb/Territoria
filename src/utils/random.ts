// Простой детерминированный хэш (Knuth multiplicative) — используется только
// для выбора оттенков/типов рельефа при рендере, не для криптографии: важны
// стабильность между рендерами и разброс, а не непредсказуемость.
export function hash(n: number): number {
  const h = Math.imul(n + 1, 2654435761);
  return (h ^ (h >>> 13)) >>> 0;
}
